#!/usr/bin/env bun
/**
 * App.Ui primitive scaffolder — the make new-feature pattern applied to
 * primitives, so adding one is one command instead of a checklist an agent
 * has to remember correctly (docs/conventions/component-checklist.md §3).
 *
 * Usage:
 *   bun scripts/new-ui-primitive.js --name=Accordion [--vendor=accordion]
 *
 * --vendor defaults to lowercase(--name). Pass it explicitly when DaisyUI's
 * own name doesn't match (e.g. App.Ui.Form wraps DaisyUI's "fieldset", not
 * "form" -- check docs/conventions/ui-coverage.md's "Vendor docs without
 * App.Ui wrapper yet" section, regenerated by `make ui-coverage`, if the
 * expected name isn't found).
 */

import { exists, readText, ROOT, run, writeText } from "./lib/repo.js";

const args = process.argv.slice(2);
let name = "";
let vendor = "";

for (const arg of args) {
  if (arg.startsWith("--name=")) name = arg.slice(7);
  else if (arg.startsWith("--vendor=")) vendor = arg.slice(9);
}

if (!name) {
  console.error("Error: --name is required (PascalCase, e.g. Accordion)");
  process.exit(1);
}

if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
  console.error(`Error: --name must be PascalCase (got: ${name})`);
  process.exit(1);
}

if (!vendor) vendor = name.toLowerCase();

const modulePath = `src/App/Ui/${name}.purs`;
const moduleFile = `${ROOT}/${modulePath}`;
const vendorDocPath = `vendor/daisyui/skills/daisyui/components/${vendor}.md`;

if (await exists(moduleFile)) {
  console.error(`Error: ${modulePath} already exists.`);
  process.exit(1);
}

const contractPath = `${ROOT}/src/Policy/Contract.purs`;
const contractContent = await readText(contractPath);

if (contractContent.includes(`"${modulePath}"`)) {
  console.error(`Error: ${modulePath} is already in Policy.Contract.uiPrimitiveModules.`);
  process.exit(1);
}

if (!(await exists(`${ROOT}/${vendorDocPath}`))) {
  console.warn(
    `⚠ ${vendorDocPath} not found — either the vendor/daisyui submodule isn't` +
      ` initialized (run \`make deps\`), or DaisyUI's name for this component` +
      ` differs from "${vendor}". Check docs/conventions/ui-coverage.md's` +
      ` "Vendor docs without App.Ui wrapper yet" section (run \`make ui-coverage\`` +
      ` first if it's stale) and re-run with --vendor=<real-name> if needed.`,
  );
  console.warn(`  Scaffolding anyway — fix the header comment below by hand if the name was wrong.`);
}

const lowerName = name[0].toLowerCase() + name.slice(1);

const stub = `-- | DaisyUI ${vendor} — ${vendorDocPath}
module App.Ui.${name}
  ( ${name}Variant(..)
  , ${lowerName}
  ) where

import App.Html (Html, class_, el, text)

-- | TODO: replace with the real variants this primitive needs (read the
-- | vendor doc above first) -- typed variants, not hand-assembled class
-- | strings at call sites outside this module (docs/conventions/component-checklist.md).
data ${name}Variant = ${name}Default

renderVariant :: ${name}Variant -> String
renderVariant = case _ of
  ${name}Default -> ""

-- | TODO: implement. This stub compiles but renders an empty, unstyled div.
${lowerName} :: ${name}Variant -> Html
${lowerName} variant =
  el "div" [ class_ (renderVariant variant) ] [ text "TODO" ]
`;

await writeText(moduleFile, stub);
console.log(`  ✓ Created ${modulePath}`);

// Insert into Policy.Contract.uiPrimitiveModules, alphabetically. This is
// the only closed-set list to touch -- forbiddenImportsInFeatureViews
// derives from it.
const updatedContract = contractContent.replace(
  /(uiPrimitiveModules :: Array String\nuiPrimitiveModules =\n  \[([\s\S]*?)\])/,
  (match, whole, entries) => {
    const lines = entries
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean);
    const newEntry = `"${modulePath}"`;
    const withNew = [...lines.map((l) => l.replace(/^,\s*/, "")), newEntry]
      .filter((l, i, arr) => arr.indexOf(l) === i)
      .sort();
    const rendered = withNew
      .map((l, i) => (i === 0 ? `  [ ${l}` : `  , ${l}`))
      .join("\n");
    return `uiPrimitiveModules :: Array String\nuiPrimitiveModules =\n${rendered}\n  ]`;
  },
);

if (updatedContract === contractContent) {
  console.error(
    "Auto-wiring failed: could not find uiPrimitiveModules in src/Policy/Contract.purs. " +
      `Add "${modulePath}" to it by hand.`,
  );
  process.exit(1);
}

await writeText(contractPath, updatedContract);
console.log(`  ✓ Added ${modulePath} to Policy.Contract.uiPrimitiveModules`);

run(["make", "ui-coverage"]);
console.log(`  ✓ Regenerated docs/conventions/ui-coverage.md`);

console.log(`
Next steps:
  1. Read ${vendorDocPath}
  2. Replace the TODO variant/render logic in ${modulePath} with the real thing
  3. make gate && make test
`);
